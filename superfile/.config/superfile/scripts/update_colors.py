#!/usr/bin/env python3
"""Generate the superfile Chrysaki theme from theme.css.

This reads the central Chrysaki tokens and writes a superfile theme file.
Run it after you bump the Chrysaki submodule and regenerate theme.css.
"""
import os
import re

FALLBACKS = {
    "abyss": "#0f1117",
    "base": "#161821",
    "surface": "#1c1f2b",
    "raised": "#252836",
    "elevated": "#2e3142",
    "border": "#363a4f",
    "text-primary": "#e0e2ea",
    "text-secondary": "#a0a4b8",
    "text-muted": "#6a6e82",
    "text-inverse": "#0f1117",
    "emerald-light": "#1a8a6a",
    "teal-light": "#20969c",
    "blonde": "#fbb13c",
    "cerulean": "#3d95e0",
    "amethyst-light": "#583090",
    "error-light": "#b53f4a",
    "peridot": "#9da82a",
    "bronze": "#b38b62",
}


def read_palette(theme_path):
    """Returns a dict of Chrysaki token name to hex value."""
    with open(theme_path, "r") as handle:
        content = handle.read()
    pattern = r"@define-color\s+(chrysaki-[\w-]+)\s+(#[0-9a-fA-F]{6,8});"
    return {name: color for name, color in re.findall(pattern, content)}


def main():
    theme_path = os.path.expanduser("~/.config/theme/theme.css")
    output_path = os.path.expanduser("~/.config/superfile/theme/chrysaki.toml")

    if not os.path.exists(theme_path):
        print(f"Error: {theme_path} not found")
        return

    colors = read_palette(theme_path)
    if not colors:
        print("No colors found in theme.css")
        return

    def get(name):
        return colors.get(f"chrysaki-{name}", FALLBACKS.get(name, "#000000"))

    output = f"""##############################################
#                                            #
#              Chrysaki Theme                #
#                                            #
##############################################

# Auto-generated by superfile/scripts/update_colors.py
# Do not edit manually. Run the script to regenerate.

###############################################################################
#                           Code Syntax Highlighting                          #
###############################################################################

code_syntax_highlight = "nord"

###############################################################################
#                                 Base Colors                                 #
###############################################################################

#-- Full Screen
full_screen_fg = "{get('text-secondary')}"
full_screen_bg = "{get('abyss')}"

#-- Gradient
# superfile supports exactly two colors here.
gradient_color = ["{get('emerald-light')}", "{get('teal-light')}"]
directory_icon_color = "{get('cerulean')}"

#-- File Panel
file_panel_fg = "{get('text-secondary')}"
file_panel_bg = "{get('abyss')}"
file_panel_border = "{get('border')}"
file_panel_border_active = "{get('emerald-light')}"
file_panel_top_directory_icon = "{get('blonde')}"
file_panel_top_path = "{get('cerulean')}"
file_panel_item_selected_fg = "{get('text-primary')}"
file_panel_item_selected_bg = "{get('raised')}"

#-- Footer
footer_fg = "{get('text-muted')}"
footer_bg = "{get('base')}"
footer_border = "{get('border')}"
footer_border_active = "{get('teal-light')}"

#-- Sidebar
sidebar_fg = "{get('text-secondary')}"
sidebar_bg = "{get('surface')}"
sidebar_title = "{get('emerald-light')}"
sidebar_border = "{get('border')}"
sidebar_border_active = "{get('emerald-light')}"
sidebar_item_selected_fg = "{get('text-primary')}"
sidebar_item_selected_bg = "{get('elevated')}"
sidebar_divider = "{get('border')}"

#-- Modals
modal_fg = "{get('text-primary')}"
modal_bg = "{get('surface')}"
modal_border_active = "{get('blonde')}"
modal_cancel_fg = "{get('text-primary')}"
modal_cancel_bg = "{get('error-light')}"
modal_confirm_fg = "{get('text-inverse')}"
modal_confirm_bg = "{get('emerald-light')}"

#-- Help Menu
help_menu_hotkey = "{get('blonde')}"
help_menu_title = "{get('emerald-light')}"

#-- Special
cursor = "{get('blonde')}"
correct = "{get('emerald-light')}"
error = "{get('error-light')}"
hint = "{get('teal-light')}"
cancel = "{get('bronze')}"
"""

    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, "w") as handle:
        handle.write(output)

    print(f"Updated {output_path}")


if __name__ == "__main__":
    main()
