#!/usr/bin/env python3
import re
import os

def main():
    theme_path = os.path.expanduser("~/.config/theme/theme.css")
    # The script writes into the stow package, so the outputs stay committed.
    package_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    output_path = os.path.join(package_dir, ".config", "gtk-3.0", "gtk.css")
    gtk4_output_path = os.path.join(package_dir, ".config", "gtk-4.0", "gtk.css")

    if not os.path.exists(theme_path):
        print(f"Error: {theme_path} not found")
        return

    with open(theme_path, 'r') as f:
        content = f.read()

    colors = {}
    matches = re.findall(r'@define-color\s+((?:chrysaki|text-chrysaki)-[\w-]+)\s+(#[0-9a-fA-F]{6,8});', content)
    for name, color in matches:
        colors[name] = color

    if not colors:
        print("No colors found")
        return

    def get_col(name, fallback="#000000"):
        return colors.get(name, fallback)

    vars = {
        "bg_color": get_col("chrysaki-base", "#353535"),
        "fg_color": get_col("text-chrysaki-base", "#ffffff"),
        "base_color": get_col("chrysaki-raised", "#2d2d2d"),
        "text_color": get_col("text-chrysaki-raised", "#ffffff"),
        "selected_bg_color": get_col("chrysaki-teal", "#197278"),
        "selected_fg_color": get_col("text-chrysaki-teal", "#ffffff"),
        "tooltip_bg_color": get_col("chrysaki-blue", "#000000"),
        "tooltip_fg_color": get_col("text-chrysaki-blue", "#ffffff"),
    }

    named_colors = build_named_colors(get_col)

    gtk_css_content = f"""/* Generated by update_colors.py */

/* Color Definitions */
@define-color bg_color {vars['bg_color']};
@define-color fg_color {vars['fg_color']};
@define-color base_color {vars['base_color']};
@define-color text_color {vars['text_color']};
@define-color selected_bg_color {vars['selected_bg_color']};
@define-color selected_fg_color {vars['selected_fg_color']};
@define-color tooltip_bg_color {vars['tooltip_bg_color']};
@define-color tooltip_fg_color {vars['tooltip_fg_color']};

{named_colors}

/* Menus and popovers. Firefox and GTK3 apps draw context menus with these. */
menu, .menu, .context-menu, popover, popover > .contents, tooltip {{
    background-color: @popover_bg_color;
    color: @popover_fg_color;
}}

menuitem:hover, .menuitem:hover {{
    background-color: @selected_bg_color;
    color: @selected_fg_color;
}}

/* Apply Colors */
window {{
    background-color: @bg_color;
    color: @fg_color;
    border-color: darker(@bg_color);
}}

/* Views (File Lists, Text Areas) */
view, list, row, entry, textview {{
    background-color: @base_color;
    color: @text_color;
}}

view:selected, list:selected, row:selected {{
    background-color: @selected_bg_color;
    color: @selected_fg_color;
}}

/* Thunar Specifics */
/* Mute the backgrounds by mixing with dark neutral grey to desaturate */
.thunar .sidebar {{
    background-color: mix(@bg_color, #252525, 0.4);
}}

.thunar .view {{
    background-color: mix(@base_color, #202020, 0.4);
}}

.thunar button {{
    padding: 1px 3px;
    /* Very subtle tint of selected color on top of muted background */
    background-color: mix(@selected_bg_color, #303030, 0.15);
    border-color: mix(@selected_bg_color, #303030, 0.3);
    color: @text_color;
}}

.thunar button:hover {{
    background-color: mix(@selected_bg_color, #303030, 0.25);
}}

.thunar button label {{
    color: @text_color;
}}

/* Header Bars / Toolbars */
headerbar, toolbar {{
    background-color: @bg_color;
    color: @fg_color;
}}

/* Buttons */
button {{
    background-color: alpha(@fg_color, 0.1);
    color: @fg_color;
    border-radius: 4px;
    border: 1px solid alpha(@fg_color, 0.2);
}}

button label {{
    color: @fg_color;
}}

button:hover {{
    background-color: alpha(@fg_color, 0.2);
}}

button:active {{
    background-color: @selected_bg_color;
    color: @selected_fg_color;
}}

button:active label {{
    color: @selected_fg_color;
}}

/* Scrollbars */
scrollbar slider {{
    background-color: alpha(@fg_color, 0.2);
    min-width: 8px;
    border-radius: 4px;
}}

scrollbar slider:hover {{
    background-color: alpha(@fg_color, 0.4);
}}
"""

    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, 'w') as f:
        f.write(gtk_css_content)

    print(f"Updated {output_path}")

    gtk4_content = f"""/* Generated by update_colors.py */
/* libadwaita and GTK4 read these named colors. */

{named_colors}
"""
    os.makedirs(os.path.dirname(gtk4_output_path), exist_ok=True)
    with open(gtk4_output_path, "w") as f:
        f.write(gtk4_content)

    print(f"Updated {gtk4_output_path}")


def build_named_colors(get_col) -> str:
    """Return the Adwaita and libadwaita named colors as @define-color lines.

    GTK3 Adwaita-dark reads the theme_* names. libadwaita reads the *_bg_color
    and *_fg_color names. Both sets map to Chrysaki tokens.
    """
    mapping = {
        # GTK3 Adwaita names
        "theme_bg_color": "chrysaki-base",
        "theme_fg_color": "text-chrysaki-base",
        "theme_base_color": "chrysaki-raised",
        "theme_text_color": "text-chrysaki-raised",
        "theme_selected_bg_color": "chrysaki-teal",
        "theme_selected_fg_color": "text-chrysaki-teal",
        "borders": "chrysaki-border",
        # libadwaita names
        "accent_color": "chrysaki-teal-light",
        "accent_bg_color": "chrysaki-teal",
        "accent_fg_color": "text-chrysaki-teal",
        "destructive_color": "chrysaki-error-light",
        "destructive_bg_color": "chrysaki-error",
        "destructive_fg_color": "text-chrysaki-error",
        "success_color": "chrysaki-emerald-light",
        "success_bg_color": "chrysaki-emerald",
        "success_fg_color": "text-chrysaki-emerald",
        "warning_color": "chrysaki-blonde",
        "warning_bg_color": "chrysaki-blonde-dim",
        "warning_fg_color": "text-chrysaki-blonde-dim",
        "error_color": "chrysaki-error-light",
        "error_bg_color": "chrysaki-error",
        "error_fg_color": "text-chrysaki-error",
        "window_bg_color": "chrysaki-base",
        "window_fg_color": "text-chrysaki-base",
        "view_bg_color": "chrysaki-surface",
        "view_fg_color": "text-chrysaki-surface",
        "headerbar_bg_color": "chrysaki-abyss",
        "headerbar_fg_color": "text-chrysaki-abyss",
        "headerbar_border_color": "chrysaki-border",
        "headerbar_backdrop_color": "chrysaki-base",
        "sidebar_bg_color": "chrysaki-abyss",
        "sidebar_fg_color": "text-chrysaki-abyss",
        "sidebar_backdrop_color": "chrysaki-base",
        "card_bg_color": "chrysaki-raised",
        "card_fg_color": "text-chrysaki-raised",
        "dialog_bg_color": "chrysaki-surface",
        "dialog_fg_color": "text-chrysaki-surface",
        "popover_bg_color": "chrysaki-elevated",
        "popover_fg_color": "text-chrysaki-elevated",
        "thumbnail_bg_color": "chrysaki-raised",
        "thumbnail_fg_color": "text-chrysaki-raised",
    }
    return "\n".join(
        f"@define-color {name} {get_col(token)};" for name, token in mapping.items()
    )

if __name__ == "__main__":
    main()
