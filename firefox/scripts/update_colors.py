#!/usr/bin/env python3
"""Generate the Chrysaki userChrome.css for Firefox from theme.css.

The output lives in the dots firefox package. install_chrome.sh links it into
each Firefox profile.
"""
import os
import re
import sys

THEME_PATH = os.path.expanduser("~/.config/theme/theme.css")
PACKAGE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT_PATH = os.path.join(PACKAGE_DIR, "chrome", "userChrome.css")

# Firefox chrome variable -> Chrysaki token.
VARIABLES = {
    "--lwt-accent-color": "chrysaki-abyss",
    "--lwt-text-color": "text-chrysaki-abyss",
    "--toolbar-bgcolor": "chrysaki-base",
    "--toolbar-color": "text-chrysaki-base",
    "--toolbar-field-background-color": "chrysaki-raised",
    "--toolbar-field-color": "text-chrysaki-raised",
    "--toolbar-field-border-color": "chrysaki-border",
    "--toolbar-field-focus-background-color": "chrysaki-surface",
    "--toolbar-field-focus-color": "text-chrysaki-surface",
    "--toolbar-field-focus-border-color": "chrysaki-teal",
    "--tab-selected-bgcolor": "chrysaki-raised",
    "--tab-selected-textcolor": "text-chrysaki-raised",
    "--arrowpanel-background": "chrysaki-elevated",
    "--arrowpanel-color": "text-chrysaki-elevated",
    "--arrowpanel-border-color": "chrysaki-border",
    "--urlbarView-highlight-background": "chrysaki-teal",
    "--urlbarView-highlight-color": "text-chrysaki-teal",
    "--urlbar-box-bgcolor": "chrysaki-elevated",
    "--sidebar-background-color": "chrysaki-abyss",
    "--sidebar-text-color": "text-chrysaki-abyss",
    "--focus-outline-color": "chrysaki-teal-light",
    "--toolbarbutton-icon-fill": "text-chrysaki-base",
}


def read_tokens(path: str) -> dict[str, str]:
    """Return the Chrysaki tokens that theme.css defines."""
    with open(path) as f:
        content = f.read()
    pattern = r"@define-color\s+((?:text-)?chrysaki-[\w-]+)\s+(#[0-9a-fA-F]{6,8});"
    return dict(re.findall(pattern, content))


def render(tokens: dict[str, str]) -> str:
    """Return the userChrome.css text."""
    missing = sorted({t for t in VARIABLES.values() if t not in tokens})
    if missing:
        raise KeyError(f"theme.css lacks tokens: {', '.join(missing)}")
    lines = [f"    {var}: {tokens[tok]} !important;" for var, tok in VARIABLES.items()]
    return (
        "/* Generated by firefox/scripts/update_colors.py. Do not edit. */\n\n"
        ":root {\n" + "\n".join(lines) + "\n}\n\n"
        "#navigator-toolbox, #TabsToolbar {\n"
        "    background-color: var(--lwt-accent-color) !important;\n"
        "    color: var(--lwt-text-color) !important;\n"
        "}\n\n"
        "menupopup, panel {\n"
        "    --panel-background: var(--arrowpanel-background) !important;\n"
        "    --panel-color: var(--arrowpanel-color) !important;\n"
        "    --panel-border-color: var(--arrowpanel-border-color) !important;\n"
        "}\n"
    )


def main() -> int:
    if not os.path.exists(THEME_PATH):
        print(f"Error: {THEME_PATH} not found", file=sys.stderr)
        return 1
    css = render(read_tokens(THEME_PATH))
    os.makedirs(os.path.dirname(OUTPUT_PATH), exist_ok=True)
    with open(OUTPUT_PATH, "w") as f:
        f.write(css)
    print(f"Updated {OUTPUT_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
